"""Master build entrypoint for the LEGOLAND California world.

Usage (inside ./.venv, Python 3.12):
    python -m src.build info                 # print resolved config (verify version/formats)
    python -m src.build all                  # regenerate the whole world + packs into build/
    python -m src.build world                # run a single phase
    python -m src.build validate             # structural validation suite
    python -m src.build clean                # remove the output dir

Design rules (from the brief):
  * Always generate into a CLEAN output dir; never write into a live save.
  * Idempotent + resumable; a rerun reproduces the world.
  * One controlled interpreter (Python 3.12); refuse others unless --allow-any-python.
"""
from __future__ import annotations

import argparse
import importlib
import logging
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

from . import config as cfg

LOG = logging.getLogger("legoland")
REQUIRED_PY = (3, 12)
OUTPUT_SENTINEL = ".legoland-build"  # marks a dir as ours, safe to overwrite

# phase name -> module providing run(ctx). "package" is handled in-process below.
PHASE_MODULES = {
    "world": "src.world",
    "terrain": "src.terrain",
    "rail": "src.rail",
    "structures": "src.structures",
    "rides": "src.entities",
    "datapack": "src.datapack",
    "resourcepack": "src.resourcepack",
    "validate": "src.validate",
}
# Order for `all`. Structures run BEFORE rail so the coaster corridor (incl. station
# boarding cells) is laid last and is never buried/erased by a structure's flatten —
# the line must stay rideable. `finalize` strips amulet artifacts; `package` zips; `validate` last.
ALL_SEQUENCE = ["world", "terrain", "structures", "rail", "rides",
                "datapack", "resourcepack", "finalize", "package", "validate"]


@dataclass
class BuildContext:
    out_dir: Path
    config_dir: Path
    version: cfg.VersionConfig
    transform: dict
    lands: dict
    rides: dict
    jobs: int = 1
    resume: bool = False
    force: bool = False

    @property
    def world_dir(self) -> Path:
        return self.out_dir / "world"

    @property
    def datapack_out(self) -> Path:
        # In singleplayer the datapack lives inside the world save.
        return self.world_dir / "datapacks" / "legoland"

    @property
    def resourcepack_out(self) -> Path:
        return self.out_dir / "resourcepack"


def _check_python(allow_any: bool) -> None:
    if sys.version_info[:2] != REQUIRED_PY and not allow_any:
        sys.exit(
            f"ERROR: requires Python {REQUIRED_PY[0]}.{REQUIRED_PY[1]} "
            f"(got {sys.version.split()[0]}). Activate ./.venv or pass --allow-any-python."
        )


def _setup_logging(level: str) -> None:
    logging.basicConfig(
        level=getattr(logging, level.upper(), logging.INFO),
        format="%(asctime)s %(levelname)-7s %(name)s | %(message)s",
        datefmt="%H:%M:%S",
    )


def make_context(args) -> BuildContext:
    config_dir = Path(args.config_dir)
    return BuildContext(
        out_dir=Path(args.out),
        config_dir=config_dir,
        version=cfg.load_version(config_dir),
        transform=cfg.load_transform(config_dir),
        lands=cfg.load_lands(config_dir),
        rides=cfg.load_rides(config_dir),
        jobs=args.jobs,
        resume=args.resume,
        force=args.force,
    )


def prepare_output_dir(ctx: BuildContext) -> None:
    """Guarantee a clean output dir that is unmistakably ours (never a live save)."""
    out = ctx.out_dir
    if out.exists():
        sentinel = out / OUTPUT_SENTINEL
        looks_like_save = (out / "world" / "level.dat").exists() or (out / "level.dat").exists()
        if not sentinel.exists() and looks_like_save and not ctx.force:
            sys.exit(
                f"REFUSING to overwrite {out}: looks like an existing save and lacks "
                f"the {OUTPUT_SENTINEL} marker. Pass --force only if you are certain."
            )
        if not ctx.resume:
            LOG.info("clearing output dir %s", out)
            shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / OUTPUT_SENTINEL).write_text("Generated by src.build — safe to delete.\n")


def _run_phase(name: str, ctx: BuildContext) -> None:
    if name == "package":
        return _phase_package(ctx)
    if name == "finalize":
        return _phase_finalize(ctx)
    module_path = PHASE_MODULES[name]
    mod = importlib.import_module(module_path)
    if not hasattr(mod, "run"):
        raise SystemExit(f"phase '{name}' ({module_path}) has no run(ctx)")
    LOG.info("=== phase: %s ===", name)
    mod.run(ctx)


def _phase_finalize(ctx: BuildContext) -> None:
    """Strip amulet/runtime artifacts the Minecraft client can't use.

    amulet writes entities/*.mca chunks that 26.1.2 rejects (missing Position); we place no
    pre-placed entities (ride rigs are datapack-summoned), so delete entities/ and let MC
    recreate them. Also drop the session lock / progress / .DS_Store from the save.
    """
    # 1) find a grass spawn near the park entrance, then REBUILD the authoritative level.dat
    #    with it. Rebuilding (vs patching) guarantees a deterministic level.dat (no amulet
    #    LastPlayed timestamp) and that all kid-safe fields survive amulet's chunk saves.
    if (ctx.world_dir / "level.dat").exists() and (ctx.world_dir / "region").exists():
        from .world import find_ground_spawn
        from .world.level_dat import write_level_dat
        spawn = find_ground_spawn(ctx)
        write_level_dat(ctx, spawn=spawn)

    # 2) strip artifacts (entities/ recreated by amulet but rejected by 26.1.2; lock files)
    wd = ctx.world_dir
    removed = []
    for name in ("entities", "entities 2"):
        p = wd / name
        if p.exists():
            shutil.rmtree(p)
            removed.append(name + "/")
    for name in ("session.lock", ".legoland_terrain_progress", ".DS_Store"):
        p = wd / name
        if p.exists():
            p.unlink()
            removed.append(name)
    LOG.info("finalize: removed %s", ", ".join(removed) or "(nothing to remove)")


def _zip_dir(src: Path, zip_path: Path, arc_root: str = "",
             exclude_files=frozenset(), exclude_dirs=frozenset()) -> int:
    import zipfile
    count = 0
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(src.rglob("*")):
            if p.is_dir():
                if p.name in exclude_dirs:
                    continue
                continue
            if any(part in exclude_dirs for part in p.relative_to(src).parts):
                continue
            if p.name in exclude_files:
                continue
            rel = p.relative_to(src)
            arc = f"{arc_root}/{rel}" if arc_root else str(rel)
            zf.write(p, arc)
            count += 1
    return count


