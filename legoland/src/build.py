def _phase_package(ctx: BuildContext) -> None:
    """Zip the world (with datapack inside) + the resource pack; write INSTALL.md."""
    dist = ctx.out_dir / "dist"
    dist.mkdir(parents=True, exist_ok=True)

    world_zip = dist / "LegolandCalifornia-world.zip"
    n1 = _zip_dir(ctx.world_dir, world_zip, arc_root="LEGOLAND California",
                  exclude_files={"session.lock", ".legoland_terrain_progress", ".DS_Store"},
                  exclude_dirs={"entities", "entities 2"})

    rp_zip = dist / "LegolandCalifornia-resourcepack.zip"
    n2 = _zip_dir(ctx.resourcepack_out, rp_zip, arc_root="",
                  exclude_files={".DS_Store"})

    install = INSTALL_MD.format(client=ctx.version.client_patch, world_patch=ctx.version.patch)
    (dist / "INSTALL.md").write_text(install)
    (Path("docs") / "INSTALL.md").write_text(install)
    LOG.info("package: world.zip (%d files) + resourcepack.zip (%d files) -> %s", n1, n2, dist)


