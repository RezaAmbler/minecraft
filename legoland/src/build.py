def cmd_info(ctx: BuildContext) -> None:
    v = ctx.version
    print("LEGOLAND California — resolved config")
    print(f"  world save version  : {v.patch}  DataVersion {v.data_version} (amulet output; client upgrades it)")
    print(f"  amulet game_version : {v.platform} {v.game_version}")
    print(f"  client version      : {v.client_patch}  DataVersion {v.client_data_version} (packs target this)")
    print(f"  datapack pack_format: {v.datapack_format}.{v.datapack_minor}")
    print(f"  resourcepack format : {v.resourcepack_format}.{v.resourcepack_minor}")
    tr = ctx.transform
    park = tr.get("park", {})
    scale = tr.get("scale", {})
    print(f"  park footprint      : ~{scale.get('park_blocks', '?')} blocks across "
          f"(compression {scale.get('compression_factor', '?')} m/block, "
          f"vert exag {scale.get('vertical_exaggeration', '?')}x)")
    print(f"  anchors             : {len(tr.get('anchor', []))} GPS pins")
    lands_list = cfg.lands(ctx.lands)
    mvp = cfg.mvp_lands(ctx.lands)
    print(f"  lands               : {len(lands_list)} total, {len(mvp)} MVP "
          f"-> {', '.join(l['name'] for l in lands_list)}")
    coasters = cfg.coasters(ctx.rides)
    statics = cfg.static_rides(ctx.rides)
    print(f"  coasters (rail)     : {len(coasters)} -> {', '.join(c['name'] for c in coasters)}")
    print(f"  static rides        : {len(statics)}")
    print(f"  output dir          : {ctx.out_dir}")


def cmd_clean(ctx: BuildContext) -> None:
    if ctx.out_dir.exists():
        LOG.info("removing %s", ctx.out_dir)
        shutil.rmtree(ctx.out_dir)
    else:
        LOG.info("%s does not exist; nothing to clean", ctx.out_dir)


def cmd_all(ctx: BuildContext) -> None:
    prepare_output_dir(ctx)
    for name in ALL_SEQUENCE:
        _run_phase(name, ctx)
    LOG.info("=== build complete -> %s ===", ctx.out_dir)


def cmd_phase(ctx: BuildContext, name: str) -> None:
    # single phases that produce world data ensure the output dir exists first
    if name in ("world",) and not ctx.world_dir.exists():
        prepare_output_dir(ctx)
    _run_phase(name, ctx)


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="src.build", description="Regenerate the LEGOLAND California world.")
    p.add_argument("--out", default="build", help="output directory (default: build)")
    p.add_argument("--config-dir", default="config", help="config directory (default: config)")
    p.add_argument("--jobs", type=int, default=1, help="worker count for region-batched phases")
    p.add_argument("--resume", action="store_true", help="resume into an existing output dir")
    p.add_argument("--force", action="store_true", help="override the live-save safety check")
    p.add_argument("--log-level", default="INFO", help="DEBUG/INFO/WARNING/ERROR")
    p.add_argument("--allow-any-python", action="store_true", help=argparse.SUPPRESS)

    sub = p.add_subparsers(dest="command", required=True)
    sub.add_parser("info", help="print resolved config and exit")
    sub.add_parser("clean", help="remove the output dir")
    sub.add_parser("all", help="run every phase in order")
    for name in [*PHASE_MODULES.keys(), "finalize", "package"]:
        sub.add_parser(name, help=f"run the '{name}' phase")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    _setup_logging(args.log_level)
    _check_python(args.allow_any_python)

    ctx = make_context(args)
    cmd = args.command
    if cmd == "info":
        cmd_info(ctx)
    elif cmd == "clean":
        cmd_clean(ctx)
    elif cmd == "all":
        cmd_all(ctx)
    else:
        cmd_phase(ctx, cmd)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
